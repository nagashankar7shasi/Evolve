-- ============================================================
--  Evolve+ — coupon / promo-code engine (covers early-bird pricing too).
--
--  One engine handles both "type a code at checkout" promo codes AND
--  no-code early-bird pricing: `requires_code = false` means a coupon
--  auto-applies to every eligible checkout before `ends_at`, with nothing
--  for the student to type — that's what makes it "early bird" rather than
--  "promo code". Everything else (type/value/scope/limits) is shared.
--
--  SCOPE matching (see couponAppliesToItem() in js/03f_coupons.js):
--    'all'      -> applies to any checkout (paper / pass / page / pdf)
--    'bundle'   -> item.type === 'pass' and item.id is in scope_ids
--    'paper'    -> item.type === 'paper' and item.id is in scope_ids
--    'category' -> item.type === 'paper' (via category/extraCategories/
--                  alsoListCategories) OR item.type === 'pass' (via the
--                  bundle's own .categories) intersecting scope_ids
--
--  REDEMPTION COUNTING, two layers, deliberately asymmetric:
--    - coupons.redemption_count is a plain counter on the coupon row itself,
--      incremented at ORDER-APPROVAL time (not at submit time -- a pending
--      claim that gets rejected must not burn a redemption slot). It's
--      publicly readable (coupons is public content, like bundles), which is
--      what lets checkout show "sorry, this one's fully redeemed" without a
--      network round trip to a sensitive table.
--    - coupon_redemptions is the detailed per-redemption log (who, which
--      order, how much) used for the PER-STUDENT limit and for the admin
--      Coupons panel's redemption list. Its SELECT is admin-only (see RLS
--      below) -- same "no-op for everyone else" posture as students/
--      student_progress already use (see fetchCloudVisitStats's comment in
--      02a_bundles.js), NOT the fully-public-read posture payment_orders
--      has. Consequence: a student's browser can't warn pre-submission
--      "you already used this code" -- that check only happens
--      authoritatively when the admin approves the order (same place the
--      app already catches a reused/duplicate UTR -- see utrDuplicateOrders
--      in js/03d_payment_claims.js). This whole app's real enforcement
--      boundary is the admin visually confirming the bank statement before
--      approving, not client-side validation, so that's an acceptable gap,
--      not a new hole.
--
--  payment_orders gets three new nullable columns rather than changing what
--  `amount` means: `amount` STAYS "what was actually charged" everywhere
--  (orderNetAmount, revenue totals, refunds all keep working unmodified).
--  `original_amount` is only set when a coupon was applied (the pre-discount
--  price, for display/audit); `coupon_code`/`discount_amount` ride along for
--  the same reason.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.coupons (
  id                      text PRIMARY KEY,
  code                    text,                         -- null when requires_code = false (early-bird)
  label                   text NOT NULL DEFAULT '',      -- admin-facing name, e.g. "Diwali Sale" / "KAS Prelims Early Bird"
  type                    text NOT NULL DEFAULT 'percent' CHECK (type IN ('percent', 'flat')),
  value                   numeric NOT NULL DEFAULT 0,
  max_discount            numeric,                       -- cap for percent-type; null = uncapped
  scope                   text NOT NULL DEFAULT 'all' CHECK (scope IN ('all', 'bundle', 'paper', 'category')),
  scope_ids               jsonb NOT NULL DEFAULT '[]'::jsonb,
  min_order_amount        numeric NOT NULL DEFAULT 0,
  starts_at               timestamptz,
  ends_at                 timestamptz,
  requires_code           boolean NOT NULL DEFAULT true,
  usage_limit_total       integer,                       -- null = unlimited
  usage_limit_per_student integer NOT NULL DEFAULT 1,
  redemption_count        integer NOT NULL DEFAULT 0,
  active                  boolean NOT NULL DEFAULT true,
  created_at              timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Case-insensitive uniqueness on code, but only while it's actually code-based -- several no-code
-- (requires_code = false) rows legitimately have code IS NULL, which a plain UNIQUE constraint would
-- otherwise also try to dedupe (though NULLs don't conflict under standard SQL uniqueness anyway,
-- this is explicit about the real intent: codes are what must be unique, not rows).
CREATE UNIQUE INDEX IF NOT EXISTS coupons_code_unique_ci
  ON public.coupons (upper(code))
  WHERE code IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.coupon_redemptions (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coupon_id       text NOT NULL REFERENCES public.coupons(id) ON DELETE CASCADE,
  student_email   text NOT NULL,
  order_id        text REFERENCES public.payment_orders(id) ON DELETE SET NULL,
  discount_amount numeric NOT NULL DEFAULT 0,
  redeemed_at     timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS coupon_redemptions_coupon_idx ON public.coupon_redemptions (coupon_id);
CREATE INDEX IF NOT EXISTS coupon_redemptions_email_idx ON public.coupon_redemptions (student_email);

ALTER TABLE public.payment_orders
  ADD COLUMN IF NOT EXISTS coupon_code text,
  ADD COLUMN IF NOT EXISTS discount_amount numeric NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS original_amount numeric;

-- ---- RLS ----
ALTER TABLE public.coupons ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "coupons_read" ON public.coupons;
CREATE POLICY "coupons_read" ON public.coupons FOR SELECT USING (true);
DROP POLICY IF EXISTS "coupons_admin_write" ON public.coupons;
CREATE POLICY "coupons_admin_write" ON public.coupons FOR ALL
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

ALTER TABLE public.coupon_redemptions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "coupon_redemptions_admin_read" ON public.coupon_redemptions;
CREATE POLICY "coupon_redemptions_admin_read" ON public.coupon_redemptions
  FOR SELECT USING (auth.role() = 'authenticated');
DROP POLICY IF EXISTS "coupon_redemptions_admin_write" ON public.coupon_redemptions;
CREATE POLICY "coupon_redemptions_admin_write" ON public.coupon_redemptions
  FOR ALL USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

GRANT SELECT ON public.coupons TO anon, authenticated;
GRANT ALL ON public.coupons TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.coupon_redemptions TO authenticated;

