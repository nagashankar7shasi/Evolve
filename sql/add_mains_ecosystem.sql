-- ============================================================
--  Evolve+ — Mains (descriptive-answer) ecosystem
--
--  Scope: KPSC KAS + UPSC CSE only (category_id IN ('kpsc_kas','upsc_cse')) --
--  Karnataka PSI / KPSC FDA-SDA are prelims-only objective exams, no Mains
--  stage, so nothing here applies to them. category_id is plain text, not a
--  DB foreign key, matching how tests_catalog.category already works --
--  EXAM_CATEGORIES is admin-editable cloud data, not a fixed SQL table.
--
--  THREE EVALUATION TIERS on one shared mains_submissions row (a student can
--  use any or all of them on the same answer):
--    1. Self-assessment -- free, client-side only, compares the student's own
--       answer against model_answer/rubric on mains_questions. No new write
--       path at all; nothing to build server-side for this tier.
--    2. AI-assisted -- a Supabase Edge Function (service-role key, so a
--       student's anon-key browser session can NEVER forge a score by
--       writing to mains_ai_evaluations directly -- see RLS below) calls an
--       LLM behind a provider-agnostic interface. Claude is the only adapter
--       wired up today; the interface is shaped so a second provider is a
--       new adapter file, not a rework. Costs a credit (mains_eval_credits).
--    3. Human (by the admin) -- ad hoc, no hard cap, no promised SLA. Paid
--       per submission, queued in mains_human_evaluations, worked through
--       whenever the admin has time -- same spirit as the payment-claims
--       queue already in this app.
--
--  RLS follows this app's existing, deliberate two-tier convention (see
--  add_coupons_and_redemptions.sql for the fuller rationale): content/state a
--  student's own anon-key browser must read back (questions, submissions,
--  evaluations, credit balance) is public-SELECT with writes restricted to
--  admin or the service-role Edge Function; purely internal admin accounting
--  (the credit ledger) is admin-only to read, same posture as
--  coupon_redemptions. Students are never Supabase Auth users in this app
--  (separate password_hash/OTP system against `students`), so there is no
--  per-user RLS scoping available here -- "a student's browser can read
--  anyone's row if they guess the id" is the same trade-off payment_orders
--  already makes, not a new one introduced by this feature.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.mains_questions (
  id              text PRIMARY KEY,
  category_id     text NOT NULL CHECK (category_id IN ('kpsc_kas', 'upsc_cse')),
  subject         text NOT NULL DEFAULT '',   -- from the existing examSubjects[category_id] registry
  question        text NOT NULL,
  model_answer    text NOT NULL DEFAULT '',
  -- Array of {criterion: text, weight: number} -- weights are expected to sum to ~100 but this isn't
  -- enforced in SQL; the admin Studio UI is responsible for that. Shared by self-assessment (rendered
  -- as a checklist) and AI evaluation (graded criterion-by-criterion) so both modes grade the same way.
  rubric          jsonb NOT NULL DEFAULT '[]'::jsonb,
  marks           numeric NOT NULL DEFAULT 10,
  word_limit      integer,
  previous_year   integer,                    -- e.g. 2023, null if not a real previous-year question
  source_note     text,                       -- e.g. "UPSC CSE 2023 GS1" -- admin-facing provenance
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS mains_questions_category_idx ON public.mains_questions (category_id);

CREATE TABLE IF NOT EXISTS public.mains_submissions (
  id                 text PRIMARY KEY,
  question_id        text NOT NULL REFERENCES public.mains_questions(id) ON DELETE CASCADE,
  student_email      text NOT NULL,
  answer_text        text,                    -- null if photo-only
  answer_image_path  text,                    -- storage path in the private 'mains_answer_photos' bucket; null if typed-only
  wants_human_eval   boolean NOT NULL DEFAULT false,
  human_eval_order_id text REFERENCES public.payment_orders(id) ON DELETE SET NULL, -- set once the paid request exists
  submitted_at       timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS mains_submissions_student_idx ON public.mains_submissions (student_email);
CREATE INDEX IF NOT EXISTS mains_submissions_question_idx ON public.mains_submissions (question_id);

CREATE TABLE IF NOT EXISTS public.mains_ai_evaluations (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id      text NOT NULL REFERENCES public.mains_submissions(id) ON DELETE CASCADE,
  overall_score      numeric NOT NULL DEFAULT 0,
  max_score          numeric NOT NULL DEFAULT 0,
  criteria_scores    jsonb NOT NULL DEFAULT '[]'::jsonb, -- [{criterion, score, max, comment}, ...]
  summary_feedback   text NOT NULL DEFAULT '',
  model_used         text,                    -- e.g. 'claude-sonnet-4-6' -- audit trail, not shown to students
  created_at         timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS mains_ai_evaluations_submission_idx ON public.mains_ai_evaluations (submission_id);

CREATE TABLE IF NOT EXISTS public.mains_human_evaluations (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id      text NOT NULL REFERENCES public.mains_submissions(id) ON DELETE CASCADE,
  status             text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done')),
  score              numeric,
  max_score          numeric,
  feedback           text,
  evaluated_at       timestamptz,
  created_at         timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS mains_human_evaluations_submission_idx ON public.mains_human_evaluations (submission_id);
CREATE INDEX IF NOT EXISTS mains_human_evaluations_status_idx ON public.mains_human_evaluations (status);

-- One row per student: current spendable balance. bundle_allowance_refreshed_at lets the app grant the
-- monthly bundle-included fair-use allowance lazily (checked whenever the student opens Mains, no cron
-- needed -- this app has none) without double-granting twice in the same cycle.
CREATE TABLE IF NOT EXISTS public.mains_eval_credits (
  student_email               text PRIMARY KEY,
  balance                     integer NOT NULL DEFAULT 0,
  bundle_allowance_refreshed_at timestamptz,
  updated_at                  timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Admin-facing audit ledger -- every grant and every spend, so "why is this student's balance what it
-- is" is always answerable. Not read by student browsers (see RLS); mains_eval_credits.balance is the
-- only number a student's own UI needs.
CREATE TABLE IF NOT EXISTS public.mains_eval_credit_transactions (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_email   text NOT NULL,
  delta           integer NOT NULL,            -- positive = grant/purchase, negative = spend
  reason          text NOT NULL CHECK (reason IN ('purchase', 'bundle_monthly_grant', 'ai_evaluation_consumed', 'admin_adjustment')),
  order_id        text REFERENCES public.payment_orders(id) ON DELETE SET NULL,
  submission_id   text REFERENCES public.mains_submissions(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS mains_eval_credit_transactions_student_idx ON public.mains_eval_credit_transactions (student_email);

-- ---- RLS ----
ALTER TABLE public.mains_questions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_questions_read" ON public.mains_questions FOR SELECT USING (true);
CREATE POLICY "mains_questions_admin_write" ON public.mains_questions FOR ALL
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

ALTER TABLE public.mains_submissions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_submissions_read" ON public.mains_submissions FOR SELECT USING (true);
-- Any anon insert allowed (a student submitting their own answer) -- same trust model as payment claim
-- inserts elsewhere in this app. Update/delete restricted to admin (e.g. clearing a submission).
CREATE POLICY "mains_submissions_insert" ON public.mains_submissions FOR INSERT WITH CHECK (true);
CREATE POLICY "mains_submissions_admin_modify" ON public.mains_submissions FOR UPDATE
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "mains_submissions_admin_delete" ON public.mains_submissions FOR DELETE
  USING (auth.role() = 'authenticated');

-- Public SELECT so a student's own browser can read their feedback; INSERT/UPDATE/DELETE restricted to
-- the authenticated-admin role. The AI-eval Edge Function writes here with the SERVICE-ROLE key, which
-- bypasses RLS entirely -- that's deliberate: it's the only way a row in this table gets created, so a
-- student's anon-key session can never insert a fake score for themselves.
ALTER TABLE public.mains_ai_evaluations ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_ai_evaluations_read" ON public.mains_ai_evaluations FOR SELECT USING (true);
CREATE POLICY "mains_ai_evaluations_admin_write" ON public.mains_ai_evaluations FOR ALL
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

ALTER TABLE public.mains_human_evaluations ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_human_evaluations_read" ON public.mains_human_evaluations FOR SELECT USING (true);
CREATE POLICY "mains_human_evaluations_admin_write" ON public.mains_human_evaluations FOR ALL
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

ALTER TABLE public.mains_eval_credits ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_eval_credits_read" ON public.mains_eval_credits FOR SELECT USING (true);
CREATE POLICY "mains_eval_credits_admin_write" ON public.mains_eval_credits FOR ALL
  USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

-- Admin-only, like coupon_redemptions -- this is internal accounting detail, not something a student's
-- browser needs to read (their balance alone, from mains_eval_credits, is enough for their own UI).
ALTER TABLE public.mains_eval_credit_transactions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "mains_eval_credit_transactions_admin_read" ON public.mains_eval_credit_transactions
  FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "mains_eval_credit_transactions_admin_write" ON public.mains_eval_credit_transactions
  FOR ALL USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

GRANT SELECT ON public.mains_questions TO anon, authenticated;
GRANT ALL ON public.mains_questions TO authenticated;
GRANT SELECT, INSERT ON public.mains_submissions TO anon, authenticated;
GRANT ALL ON public.mains_submissions TO authenticated;
GRANT SELECT ON public.mains_ai_evaluations TO anon, authenticated;
GRANT ALL ON public.mains_ai_evaluations TO authenticated;
GRANT SELECT ON public.mains_human_evaluations TO anon, authenticated;
GRANT ALL ON public.mains_human_evaluations TO authenticated;
GRANT SELECT ON public.mains_eval_credits TO anon, authenticated;
GRANT ALL ON public.mains_eval_credits TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.mains_eval_credit_transactions TO authenticated;

-- ---- Storage: private bucket for handwritten-answer photos (same pattern as pdf_vault_files in
-- sql/fix_pdf_vault_private_bucket.sql) -- NOT public, because a student's answer photo shouldn't sit
-- at a permanent, guessable URL. The app reads it via a short-lived signed URL it mints after checking
-- access (and the AI Edge Function reads it server-side with the service-role key).
INSERT INTO storage.buckets (id, name, public)
VALUES ('mains_answer_photos', 'mains_answer_photos', false)
ON CONFLICT (id) DO UPDATE SET public = false;

CREATE POLICY "mains_answer_photos select" ON storage.objects FOR SELECT
  USING (bucket_id = 'mains_answer_photos');
CREATE POLICY "mains_answer_photos insert" ON storage.objects FOR INSERT
  WITH CHECK (bucket_id = 'mains_answer_photos');
CREATE POLICY "mains_answer_photos update" ON storage.objects FOR UPDATE
  USING (bucket_id = 'mains_answer_photos') WITH CHECK (bucket_id = 'mains_answer_photos');
CREATE POLICY "mains_answer_photos delete" ON storage.objects FOR DELETE
  USING (bucket_id = 'mains_answer_photos');

