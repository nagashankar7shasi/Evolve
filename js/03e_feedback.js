    function afterStudentDataChange() {
      renderPaymentOrders();
      if (currentAdminPanel === 'overview') renderOverview();
      if (currentAdminPanel === 'revenue') renderRevenue();
      renderStudentEntitlementsDesk();
      if (typeof renderStudentDirectoryTable === 'function') renderStudentDirectoryTable();
      if (activeSelectedStudent) {
        const fresh = getStudentRecord(activeSelectedStudent.email);
        if (fresh) selectStudent(fresh);
      }
      refreshUserScopedViews();
    }

    // Manual resync for admins working across multiple tabs/devices. There's no realtime push in
    // this app — each browser only knows what it fetched at load time — so approving a payment on
    // one device won't be visible on another until either a reload or this explicit refresh. This
    // directly addresses "entitlements shown when verifying are different from Access Desk" reports,
    // which happen when two admin sessions are open at once.
    async function refreshStudentDataFromCloud() {
      const btn = document.getElementById('refresh-entitlements-btn');
      const oldText = btn.innerText;
      btn.disabled = true;
      btn.innerText = '🔄 Refreshing…';
      try {
        await fetchCloudStudents();
        await fetchCloudPayments();
        await fetchCloudAllProgress();
        afterStudentDataChange();
        btn.innerText = '✓ Up to date';
      } catch (err) {
        console.error('refreshStudentDataFromCloud failed:', fmtErr(err));
        btn.innerText = '⚠ Refresh failed';
      } finally {
        setTimeout(() => { btn.disabled = false; btn.innerText = oldText; }, 2000);
      }
    }

