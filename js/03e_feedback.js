    /* ----------------------------------------------------
       FEEDBACK — a public "message + email + WhatsApp" form (floating button,
       bottom-right, all pages) that writes to a `feedback_log` Supabase table,
       plus an admin panel tab to read/manage what comes in. Follows the exact
       same "table might not exist yet, show the one-time setup SQL" pattern
       already used for home_config, so it degrades the same way everywhere.
    ----------------------------------------------------- */
    let feedbackLog = [];

    function openFeedbackModal() {
      document.getElementById('feedback-modal').classList.remove('hidden');
      document.getElementById('feedback-msg').classList.add('hidden');
      document.getElementById('feedback-message').value = '';
      document.getElementById('feedback-email').value = currentUser?.email || '';
      document.getElementById('feedback-whatsapp').value = '';
      setTimeout(() => document.getElementById('feedback-message').focus(), 50);
    }

    function closeFeedbackModal() {
      document.getElementById('feedback-modal').classList.add('hidden');
    }

    function showFeedbackMsg(text, type = 'error') {
      const el = document.getElementById('feedback-msg');
      const styles = {
        error: 'bg-rose-50 text-rose-800 border-rose-200',
        success: 'bg-emerald-50 text-emerald-800 border-emerald-200'
      };
      el.className = `p-2.5 rounded-lg text-xs border ${styles[type] || styles.error}`;
      el.innerText = text;
      el.classList.remove('hidden');
    }

    async function submitFeedback() {
      const message = document.getElementById('feedback-message').value.trim();
      const email = document.getElementById('feedback-email').value.trim();
      const whatsapp = document.getElementById('feedback-whatsapp').value.trim();
      if (!message) return showFeedbackMsg('Please enter a message before sending.');

      const btn = document.getElementById('feedback-submit-btn');
      const originalText = btn.innerText;
      btn.innerText = 'Sending…';
      btn.disabled = true;

      const row = {
        message,
        email: email || null,
        whatsapp: whatsapp || null,
        page_context: (document.title || '').slice(0, 200),
        status: 'new'
      };

      const { error } = await supabaseClient.from('feedback_log').insert([row]);

      btn.innerText = originalText;
      btn.disabled = false;

      if (error) {
        console.error('Feedback insert failed:', fmtErr(error));
        const msg = String(error.message || error);
        const isMissing = /relation .*feedback_log.* does not exist|table.*feedback_log|Could not find the table/i.test(msg);
        if (isMissing) {
          showFeedbackMsg("This feature isn't fully set up yet on our end — please try again shortly, or reach us another way in the meantime.");
          console.warn(
            "The `feedback_log` table doesn't exist in Supabase yet. One-time setup (SQL Editor → New query):\n\n" +
            "CREATE TABLE IF NOT EXISTS public.feedback_log (\n" +
            "  id bigint generated by default as identity primary key,\n" +
            "  message text NOT NULL,\n" +
            "  email text,\n" +
            "  whatsapp text,\n" +
            "  page_context text,\n" +
            "  status text DEFAULT 'new',\n" +
            "  created_at timestamptz DEFAULT now()\n" +
            ");\n" +
            "ALTER TABLE public.feedback_log ENABLE ROW LEVEL SECURITY;\n" +
            "CREATE POLICY \"feedback_log public insert\" ON public.feedback_log FOR INSERT WITH CHECK (true);\n" +
            "CREATE POLICY \"feedback_log admin read\" ON public.feedback_log FOR SELECT USING (public.is_admin());\n" +
            "CREATE POLICY \"feedback_log admin update\" ON public.feedback_log FOR UPDATE USING (public.is_admin()) WITH CHECK (public.is_admin());\n" +
            "CREATE POLICY \"feedback_log admin delete\" ON public.feedback_log FOR DELETE USING (public.is_admin());"
          );
        } else {
          showFeedbackMsg('Could not send right now: ' + msg);
        }
        return;
      }

      showFeedbackMsg("Thanks — your feedback's been sent!", 'success');
      setTimeout(closeFeedbackModal, 1400);
    }

    async function fetchCloudFeedback() {
      const { data, error } = await supabaseClient
        .from('feedback_log')
        .select('*')
        .order('created_at', { ascending: false });
      if (error) {
        console.error('Failed to fetch feedback_log:', fmtErr(error));
        feedbackLog = [];
        return;
      }
      feedbackLog = data || [];
    }

    function renderFeedbackAdmin() {
      const root = document.getElementById('feedback-admin-list');
      if (!root) return;
      root.innerHTML = '<p class="text-slate-400 text-center py-6">Loading…</p>';
      fetchCloudFeedback().then(() => {
        const newCount = feedbackLog.filter(f => f.status === 'new').length;
        const badgeEl = document.getElementById('feedback-nav-badge');
        if (badgeEl) { badgeEl.innerText = newCount; badgeEl.classList.toggle('hidden', !newCount); }

        if (!feedbackLog.length) {
          root.innerHTML = '<p class="text-slate-400 text-center py-6 text-xs">No feedback yet. The form is live on every page (bottom-right "💬 Feedback" button).</p>';
          return;
        }
        root.innerHTML = feedbackLog.map(f => `
          <div class="p-3.5 rounded-xl border ${f.status === 'new' ? 'border-amber-300 bg-amber-50/40' : 'border-slate-200 bg-white'} space-y-1.5">
            <div class="flex items-start justify-between gap-2">
              <p class="text-xs text-slate-800 whitespace-pre-wrap flex-1">${escapeHtml(f.message)}</p>
              ${f.status === 'new' ? '<span class="shrink-0 text-[9px] font-bold uppercase bg-amber-500 text-slate-950 px-1.5 py-0.5 rounded-full">New</span>' : ''}
            </div>
            <div class="flex flex-wrap gap-x-3 gap-y-0.5 text-[10px] text-slate-500">
              <span>${fmtDateTime(f.created_at)}</span>
              ${f.email ? `<a href="mailto:${escapeHtml(f.email)}" class="text-amber-700 hover:underline">✉️ ${escapeHtml(f.email)}</a>` : ''}
              ${f.whatsapp ? `<a href="https://wa.me/${escapeHtml(String(f.whatsapp).replace(/[^\d+]/g, ''))}" target="_blank" rel="noopener" class="text-emerald-700 hover:underline">💬 ${escapeHtml(f.whatsapp)}</a>` : ''}
              ${f.page_context ? `<span class="text-slate-400">from: ${escapeHtml(f.page_context)}</span>` : ''}
            </div>
            <div class="flex gap-2 pt-1">
              ${f.status === 'new'
                ? `<button onclick="markFeedbackRead(${f.id})" class="text-[10px] font-bold text-emerald-700 hover:underline">Mark as read</button>`
                : `<span class="text-[10px] text-slate-400">Read</span>`}
              <button onclick="deleteFeedback(${f.id})" class="text-[10px] font-bold text-rose-600 hover:underline">Delete</button>
            </div>
          </div>
        `).join('');
      });
    }

    async function markFeedbackRead(id) {
      const { error } = await supabaseClient.from('feedback_log').update({ status: 'read' }).eq('id', id);
      if (error) return alert('Could not update: ' + fmtErr(error));
      const item = feedbackLog.find(f => f.id === id);
      if (item) item.status = 'read';
      renderFeedbackAdmin();
    }

    async function deleteFeedback(id) {
      if (!confirm('Delete this feedback entry? This cannot be undone.')) return;
      const { error } = await supabaseClient.from('feedback_log').delete().eq('id', id);
      if (error) return alert('Could not delete: ' + fmtErr(error));
      feedbackLog = feedbackLog.filter(f => f.id !== id);
      renderFeedbackAdmin();
    }

